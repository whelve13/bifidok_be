def generate_global_universe():
    print(f"Base seed companies: {len(GLOBAL_COMPANIES)}")
    # We also import existing additional enterprises from expanded_enterprises and historical_harvester
    from expanded_enterprises import ADDITIONAL_EUROPEAN_ENTERPRISES
    
    seen_names = set()
    unified = []
    
    for c in GLOBAL_COMPANIES:
        name = c["name"].strip()
        if name.lower() not in seen_names:
            seen_names.add(name.lower())
            unified.append(c)
            
    for c in ADDITIONAL_EUROPEAN_ENTERPRISES:
        name = c["name"].strip()
        if name.lower() not in seen_names:
            seen_names.add(name.lower())
            # Ensure country is populated
            if not c.get("country"):
                c["country"] = "DE" if "gmbh" in name.lower() or "ag" in name.lower() else "EU"
            unified.append(c)

    print(f"Total unified unique global companies: {len(unified)}")
    
    with open(OUT_FILE, "w", encoding="utf-8") as f:
        f.write('"""\nGlobal Enterprise Market Universe.\nCurated unique global enterprises across North America, Europe, UK, APAC, and Latin America.\n"""\nfrom typing import Any, Dict, List\n\n')
        f.write("GLOBAL_ENTERPRISE_UNIVERSE: List[Dict[str, Any]] = ")
        f.write(json.dumps(unified, indent=4))
        f.write("\n")

    print(f"Successfully generated {OUT_FILE} with {len(unified)} distinct companies.")

if __name__ == "__main__":
    generate_global_universe()
