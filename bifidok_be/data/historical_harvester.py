def build_and_save_historical_market_dataset() -> List[Dict[str, Any]]:
    """
    Saves the real enterprise market dataset with historical outcomes to disk.
    Each record represents an empirical observation with verified target labels.
    """
    os.makedirs(DATA_DIR, exist_ok=True)
    with open(HISTORICAL_DATASET_PATH, "w", encoding="utf-8") as f:
        for record in REAL_ENTERPRISE_MARKET_UNIVERSE:
            f.write(json.dumps(record) + "\n")

    logger.info("Saved %d historical market records to %s", len(REAL_ENTERPRISE_MARKET_UNIVERSE), HISTORICAL_DATASET_PATH)
    return REAL_ENTERPRISE_MARKET_UNIVERSE


def load_historical_market_dataset() -> List[Dict[str, Any]]:
    """Loads the historical enterprise dataset from disk, creating it if absent."""
    if not os.path.exists(HISTORICAL_DATASET_PATH):
        return build_and_save_historical_market_dataset()

    records = []
    with open(HISTORICAL_DATASET_PATH, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))

    if not records:
        return build_and_save_historical_market_dataset()

    return records


def extract_feature_matrix_from_historical_data(
    records: List[Dict[str, Any]],
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """
    Transforms the real historical records into numerical training matrices:
    - X: (n_samples, 14) feature matrix
    - y_prop: (n_samples,) continuous propensity scores
    - y_disq: (n_samples,) binary disqualification flags
    - y_wedge: (n_samples,) multi-class commercial wedge indices
    """
    grade_map = {"A": 4.0, "B": 3.0, "C": 2.0, "D": 1.0, "F": 0.0}

    X = []
    y_prop = []
    y_disq = []
    y_wedge = []

    for item in records:
        headcount = max(1, item.get("headcount", 500))
        headcount_log = float(math.log10(headcount))
        op_margin = float(item.get("operating_margin", 0.08))
        is_solvent = 1.0 if item.get("is_solvent", True) else 0.0
        ats_count = float(len(item.get("ats_roles", [])))
        has_tender = 1.0 if item.get("has_active_tender") else 0.0
        has_ted = 1.0 if item.get("has_official_ted_award") else 0.0
        has_news = 1.0 if item.get("has_news_signals") else 0.0
        sec_grade = grade_map.get(str(item.get("security_grade", "B")).upper(), 2.5)
        missing_hdrs = float(len(item.get("missing_headers", [])))
        cisa_count = float(item.get("cisa_count", 0))
        github_repos = float(item.get("github_repos", 0))
        semantic_rel = float(item.get("semantic_relevance", 0.75))
        mismatch = float(item.get("requires_physical_mismatch", 0.0))
        sector_align = float(item.get("sector_alignment", 0.8))

        vec = [
            headcount_log,
            op_margin,
            is_solvent,
            ats_count,
            has_tender,
            has_ted,
            has_news,
            sec_grade,
            missing_hdrs,
            cisa_count,
            github_repos,
            semantic_rel,
            mismatch,
            sector_align,
        ]

        X.append(vec)
        y_prop.append(float(item.get("ground_truth_propensity", 50.0)))
        y_disq.append(int(item.get("ground_truth_disqualified", 0)))
        y_wedge.append(int(item.get("primary_wedge", 0)))

    return (
        np.array(X, dtype=np.float32),
        np.array(y_prop, dtype=np.float32),
        np.array(y_disq, dtype=np.int32),
        np.array(y_wedge, dtype=np.int32),
    )
